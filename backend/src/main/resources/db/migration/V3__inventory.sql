-- ================= KHO HANG =================
-- Ton kho tinh theo DON VI GOC cua san pham (product.unit, la don vi ban). Moi thay doi ton deu qua stock_movement (so kho,
-- khong sua/xoa); stock_balance la so du hien tai, cap nhat CUNG transaction voi so kho. Bat bien: on_hand = SUM(qty).

ALTER TABLE product ADD COLUMN min_stock NUMERIC(14,3) NOT NULL DEFAULT 0;

-- Gia von cua dong hang luc chot (= gia tri xuat kho). NULL: chua biet gia von (chua tung nhap hang).
ALTER TABLE order_item ADD COLUMN cost_total NUMERIC(18,2);

-- Don vi quy doi khi nhap: 1 <unit> = ratio <don vi goc>. Vd ton ban theo m, nhap theo kg: 1 kg = 0.318 m.
CREATE TABLE product_unit (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT        NOT NULL REFERENCES product(id) ON DELETE CASCADE,
  unit       VARCHAR(50)   NOT NULL,
  ratio      NUMERIC(18,6) NOT NULL,
  CONSTRAINT ux_product_unit UNIQUE (product_id, unit)
);

CREATE TABLE stock_balance (
  product_id BIGINT        PRIMARY KEY REFERENCES product(id),
  on_hand    NUMERIC(14,3) NOT NULL DEFAULT 0,
  avg_cost   NUMERIC(18,4) NOT NULL DEFAULT 0,
  version    BIGINT        NOT NULL DEFAULT 0
);
INSERT INTO stock_balance (product_id) SELECT id FROM product;

-- type: RECEIPT, RECEIPT_CANCEL, SALE, SALE_CANCEL, COUNT, ADJUST. qty co dau (+ nhap, - xuat).
CREATE TABLE stock_movement (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     BIGINT        NOT NULL REFERENCES product(id),
  type           VARCHAR(20)   NOT NULL,
  qty            NUMERIC(14,3) NOT NULL,
  unit_cost      NUMERIC(18,4) NOT NULL,
  amount         NUMERIC(18,2) NOT NULL,   -- gia tri = qty x unit_cost (co dau); "value" la tu khoa H2
  balance_after  NUMERIC(14,3) NOT NULL,
  avg_cost_after NUMERIC(18,4) NOT NULL,
  ref_type       VARCHAR(20)   NOT NULL,
  ref_id         BIGINT,
  ref_line_id    BIGINT,
  ref_code       VARCHAR(20),
  note           VARCHAR(300),
  created_by     VARCHAR(100),
  created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Chan ghi so 2 lan cho cung 1 dong chung tu (bam "Ghi so" 2 lan, retry mang...)
CREATE UNIQUE INDEX ux_stock_move_ref ON stock_movement(ref_type, ref_id, ref_line_id, type);
CREATE INDEX idx_stock_move_product ON stock_movement(product_id, id);
CREATE INDEX idx_stock_move_created ON stock_movement(created_at);

-- ================= NHA CUNG CAP + CONG NO NCC (cung mau voi khach hang) =================
CREATE TABLE supplier (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(150)  NOT NULL,
  phone      VARCHAR(30),
  address    VARCHAR(200),
  debt       NUMERIC(18,2) NOT NULL DEFAULT 0,
  active     BOOLEAN       NOT NULL DEFAULT TRUE,
  version    BIGINT        NOT NULL DEFAULT 0,
  created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- type: RECEIPT (nhap chiu, no tang), PAYMENT (tra NCC), CANCEL (huy phieu nhap), MANUAL (no ban dau / sua tay)
CREATE TABLE supplier_ledger (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_id   BIGINT        NOT NULL REFERENCES supplier(id),
  type          VARCHAR(20)   NOT NULL,
  amount        NUMERIC(18,2) NOT NULL,
  balance_after NUMERIC(18,2) NOT NULL,
  receipt_id    BIGINT,
  note          VARCHAR(300),
  created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_supplier_ledger ON supplier_ledger(supplier_id, id);

-- ================= PHIEU NHAP =================
CREATE SEQUENCE receipt_code_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE goods_receipt (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(20)   UNIQUE,            -- PNxxxxxx, cap khi ghi so
  status        VARCHAR(20)   NOT NULL,          -- DRAFT, POSTED, CANCELLED
  supplier_id   BIGINT        REFERENCES supplier(id),
  supplier_name VARCHAR(150),
  note          VARCHAR(300),
  total         NUMERIC(18,2) NOT NULL DEFAULT 0,
  paid_amount   NUMERIC(18,2) NOT NULL DEFAULT 0,
  created_by    VARCHAR(100),
  created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  posted_at     TIMESTAMP,
  cancelled_at  TIMESTAMP
);
CREATE INDEX idx_receipt_status_date ON goods_receipt(status, posted_at);

CREATE TABLE goods_receipt_line (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_id   BIGINT        NOT NULL REFERENCES goods_receipt(id) ON DELETE CASCADE,
  product_id   BIGINT        NOT NULL REFERENCES product(id),
  product_name VARCHAR(150)  NOT NULL,
  unit         VARCHAR(50),                      -- don vi goc
  input_unit   VARCHAR(50),                      -- don vi nhap (kg, bo, cuon...)
  input_qty    NUMERIC(14,3) NOT NULL,
  input_price  NUMERIC(18,2) NOT NULL,           -- gia theo don vi nhap
  ratio        NUMERIC(18,6) NOT NULL,
  qty          NUMERIC(14,3) NOT NULL,           -- so luong theo don vi goc (sua duoc theo thuc te)
  unit_cost    NUMERIC(18,4) NOT NULL,           -- gia von / don vi goc = line_total / qty
  line_total   NUMERIC(18,2) NOT NULL
);
CREATE INDEX idx_receipt_line ON goods_receipt_line(receipt_id);

-- ================= KIEM KE =================
CREATE SEQUENCE count_code_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE stock_count (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code       VARCHAR(20)  UNIQUE,                -- KKxxxxxx, cap khi ghi so
  status     VARCHAR(20)  NOT NULL,              -- DRAFT, POSTED
  note       VARCHAR(300),
  created_by VARCHAR(100),
  created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  posted_at  TIMESTAMP
);

CREATE TABLE stock_count_line (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  count_id     BIGINT        NOT NULL REFERENCES stock_count(id) ON DELETE CASCADE,
  product_id   BIGINT        NOT NULL REFERENCES product(id),
  product_name VARCHAR(150)  NOT NULL,
  unit         VARCHAR(50),
  system_qty   NUMERIC(14,3),                    -- ton so sach LUC GHI SO
  counted_qty  NUMERIC(14,3),                    -- NULL = chua dem, bo qua khi ghi so
  diff         NUMERIC(14,3),
  unit_cost    NUMERIC(18,4)                     -- gia von dung de dinh gia chenh lech; NULL = lay gia von hien tai
);
CREATE INDEX idx_count_line ON stock_count_line(count_id);
