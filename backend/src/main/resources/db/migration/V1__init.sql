CREATE TABLE app_user (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  full_name     VARCHAR(100) NOT NULL,
  role          VARCHAR(20)  NOT NULL,
  active        BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE category (
  id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE product (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT REFERENCES category(id),
  name        VARCHAR(150)   NOT NULL,
  unit        VARCHAR(50),
  price       NUMERIC(18,2)  NOT NULL,
  active      BOOLEAN        NOT NULL DEFAULT TRUE,
  created_at  TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE customer (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100)  NOT NULL,
  address    VARCHAR(200),
  phone      VARCHAR(30),
  debt       NUMERIC(18,2) NOT NULL DEFAULT 0,
  active     BOOLEAN       NOT NULL DEFAULT TRUE,
  version    BIGINT        NOT NULL DEFAULT 0,
  created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE SEQUENCE order_code_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE orders (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(20)   NOT NULL UNIQUE,
  status           VARCHAR(20)   NOT NULL,
  customer_id      BIGINT REFERENCES customer(id),
  customer_name    VARCHAR(100),
  customer_address VARCHAR(200),
  customer_phone   VARCHAR(30),
  staff_name       VARCHAR(100),
  items_total      NUMERIC(18,2) NOT NULL DEFAULT 0,
  shipping_fee     NUMERIC(18,2) NOT NULL DEFAULT 0,
  previous_debt    NUMERIC(18,2) NOT NULL DEFAULT 0,
  total_payable    NUMERIC(18,2) NOT NULL DEFAULT 0,
  paid_amount      NUMERIC(18,2) NOT NULL DEFAULT 0,
  debt_after       NUMERIC(18,2) NOT NULL DEFAULT 0,
  note             VARCHAR(300),
  created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  checked_out_at   TIMESTAMP
);
CREATE INDEX idx_orders_status_checkout ON orders(status, checked_out_at);
CREATE INDEX idx_orders_customer ON orders(customer_id);

CREATE TABLE order_item (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       BIGINT        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id     BIGINT REFERENCES product(id),
  product_name   VARCHAR(150)  NOT NULL,
  unit           VARCHAR(50),
  unit_price     NUMERIC(18,2) NOT NULL,
  quantity       NUMERIC(12,3) NOT NULL,
  sheets         INT           NOT NULL DEFAULT 0,
  factor         NUMERIC(8,3)  NOT NULL DEFAULT 0,
  total_quantity NUMERIC(14,3) NOT NULL,
  line_total     NUMERIC(18,2) NOT NULL
);
CREATE INDEX idx_order_item_order ON order_item(order_id);

-- So cai cong no: moi lan no tang/giam la 1 dong, truy vet duoc khi no sai
CREATE TABLE debt_ledger (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id   BIGINT        NOT NULL REFERENCES customer(id),
  type          VARCHAR(20)   NOT NULL,
  amount        NUMERIC(18,2) NOT NULL,
  balance_after NUMERIC(18,2) NOT NULL,
  order_id      BIGINT REFERENCES orders(id),
  note          VARCHAR(300),
  created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ledger_customer ON debt_ledger(customer_id, created_at);
