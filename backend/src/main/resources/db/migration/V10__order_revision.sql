-- Lich su sua hoa don da chot (chi quan tri): ai sua, luc nao, ly do, truoc / sau.
CREATE TABLE order_revision (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    BIGINT        NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  revised_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  revised_by  VARCHAR(100),
  reason      VARCHAR(300),
  debt_delta  NUMERIC(18,2) NOT NULL DEFAULT 0,
  refund      NUMERIC(18,2) NOT NULL DEFAULT 0,
  before_text TEXT          NOT NULL,
  after_text  TEXT          NOT NULL
);
CREATE INDEX idx_order_revision ON order_revision(order_id, id);
